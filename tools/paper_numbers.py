"""
One authoritative source for every number the paper quotes (paper/review.md, concern 5).

Reads the raw data and the result files and writes, under paper/latex/generated/:
  numbers.tex        \\newcommand macros for every scalar the text cites (v3 audit and v4)
  tab_v3_*.tex       the v3 tables (text-only, options-only, gating-causality)
  tab_v4_*.tex       the v4 tables (baselines, E1-E5); cells read "--" until the v4 runs exist
  numbers.json       the same scalars, for checking

Nothing here is typed by hand: the paper cites macros and \\input's tables. Run after any change to the results:
  python -m tools.paper_numbers            # regenerate
  python -m tools.paper_numbers --check    # also fail if the .tex still contains a known stale number
"""

from __future__ import annotations

